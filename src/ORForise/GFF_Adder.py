# compute which of six frames a feature is in using GFF coords (1-based coords)
# Frames: 0,1,2 -> forward strand frames based on start position modulo 3
#         3,4,5 -> reverse strand frames based on stop position modulo 3 (offset by 3)
# Returns integer 0..5 or None if strand or coords unknown
def compute_frame(start, stop, strand):
    try:
        if start is None or stop is None:
            return None
        if strand == '+':
            return (int(start) - 1) % 3
        elif strand == '-':
            return 3 + ((int(stop) - 1) % 3)
        else:
            return None
    except Exception:
        return None


# remove any existing ID=... from an attributes string and normalise
def sanitise_attr_value(attr_text: str) -> str:
    if not attr_text:
        return ''
    s = str(attr_text).strip()
    # remove leading/trailing semicolons and whitespace
    s = s.strip(';').strip()
    # remove any ID=... tokens to avoid duplicate ID attribute
    s = re.sub(r'(^|;)\s*ID=[^;]*(;|$)', ';', s)
    # collapse repeated semicolons
    s = re.sub(r';{2,}', ';', s)
    s = s.strip(';').strip()
    return s


# Parse a plain GFF (possibly gzipped) and return mapping contig -> {"start,stop": [strand, source, type, attr, frame, start, stop]}
def parse_plain_gff_to_mapping(gff_path, dna_regions):
    mapping = defaultdict(dict)
    try:
        # detect gz
        with open(gff_path, 'rb') as _probe:
            magic = _probe.read(2)
            is_gz = (magic == b'\x1f\x8b')
    except Exception:
        is_gz = False
    try:
        fh = gzip.open(gff_path, 'rt', errors='replace') if is_gz else open(gff_path, 'r', encoding='utf-8', errors='replace')
    except Exception:
        return mapping
    try:
        for line in fh:
            if not line or line.startswith('#'):
                continue
            parts = line.strip().split('\t')
            if len(parts) < 9:
                continue
            contig = parts[0]
            try:
                start_i = int(parts[3]); stop_i = int(parts[4])
            except Exception:
                continue
            source = parts[1]; ftype = parts[2]; strand = parts[6]; attr = parts[8].lstrip(';').strip()
            frame = compute_frame(start_i, stop_i, strand)
            pos = f"{start_i},{stop_i}"
            mapping[contig][pos] = [strand, source, ftype, attr, frame, start_i, stop_i]
    finally:
        try:
            fh.close()
        except Exception:
            pass
    return mapping


